def t(key: str, lang: str = "sw", **kwargs) -> str:
    """Translate a key for the given language. Falls back to English, then the key itself."""
    table = TRANSLATIONS.get(lang, TRANSLATIONS["en"])
    value = table.get(key)
    if value is None:
        value = TRANSLATIONS["en"].get(key, key)
    if kwargs:
        try:
            value = value.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return value


